/**
 * 有序列表重编号回归（`renumberOrdered` + `collectLayerStarts` 纯函数）。
 *
 * 背景：Live Preview 显示的是源码里的数字，块移动是整段文本搬运 → 重排后序号必乱。
 * 本套件锁住重编号的语义，重点是五个易错点：
 *   ① 起始号取自**搬运前**的层快照，而非输出首行的旧号（否则 1.甲 被拖走后全段变 2/3/4）；
 *   ② 嵌套层级各自独立连号；
 *   ③ 列表项里嵌的代码围栏 / 公式块内容不得被改；
 *   ④ callout（`> `）内的列表与外部互不串号；
 *   ⑤ 保留原始首项号（3 起始的列表不被压成 1 起始）。
 *
 * 运行：node scripts/list-number-spec.mjs
 */
import { renumberOrdered, collectLayerStarts } from '../temp/verify/list-number.mjs';

let pass = 0,
  fail = 0;
const ok = (c, l) => {
  if (c) {
    pass++;
    console.log(`  PASS ${l}`);
  } else {
    fail++;
    console.log(`  FAIL ${l}`);
  }
};
const eq = (a, b, l) =>
  ok(
    JSON.stringify(a) === JSON.stringify(b),
    `${l}\n       got  ${JSON.stringify(a)}\n       want ${JSON.stringify(b)}`
  );

/** 模拟一次「整段重写」：before 是搬运前的 span，after 是重排后的新行 */
const move = (before, after) => renumberOrdered(after, { layerStarts: collectLayerStarts(before) }).lines;
/** 不带快照的纯文本重编号 */
const rn = (lines) => renumberOrdered(lines).lines;

console.log('\n=== 1. 基础：已是正确序号则不动 ===');
{
  eq(rn(['1. 甲', '2. 乙', '3. 丙']), ['1. 甲', '2. 乙', '3. 丙'], '1/2/3 原样保留');
  eq(rn(['- 甲', '- 乙']), ['- 甲', '- 乙'], '无序列表不受影响');
  eq(renumberOrdered(['1. 甲', '2. 乙']).changed, false, '无变化时 changed=false');
}

console.log('\n=== 2. 拖动重排：起始号来自搬运前的快照 ===');
{
  // 把 3.丙 拖到最前：快照里顶层起始号是 1 → 丙1 甲2 乙3
  eq(
    move(['1. 甲', '2. 乙', '3. 丙'], ['3. 丙', '1. 甲', '2. 乙']),
    ['1. 丙', '2. 甲', '3. 乙'],
    '丙拖到首位 → 1/2/3 连号'
  );

  // 关键回归：把 1.甲 拖走，剩下首行是 2.乙。
  // 若拿输出首行的旧号当锚点会变成 2/3/4；正确是回到列表原本的起始号 1。
  eq(
    move(['1. 甲', '2. 乙', '3. 丙'], ['2. 乙', '1. 甲', '3. 丙']),
    ['1. 乙', '2. 甲', '3. 丙'],
    '甲被拖到中间 → 乙回到 1 号（不被带成 2）'
  );

  eq(
    move(['1. 甲', '2. 乙', '3. 丙'], ['2. 乙', '3. 丙', '1. 甲']),
    ['1. 乙', '2. 丙', '3. 甲'],
    '甲被拖到末尾 → 乙丙从 1 重新连号'
  );
}

console.log('\n=== 3. 保留原始首项号（不从 1 重压） ===');
{
  eq(
    move(['3. 甲', '4. 乙', '5. 丙'], ['5. 丙', '3. 甲', '4. 乙']),
    ['3. 丙', '4. 甲', '5. 乙'],
    '3 起始的列表重排后仍 3 起始'
  );
  eq(rn(['5. 甲', '5. 乙']), ['5. 甲', '6. 乙'], '5,5 → 5,6（不从 1 重压）');
}

console.log('\n=== 4. 嵌套层级各自连号 ===');
{
  eq(
    move(['1. 甲', '   1. 子1', '   2. 子2', '2. 乙'], ['1. 甲', '2. 乙', '   1. 子1', '   2. 子2']),
    ['1. 甲', '2. 乙', '   1. 子1', '   2. 子2'],
    '顶层重排时子层级保持自己的连号'
  );

  // 子层级起始号独立锚定：子层原本 3 起始
  eq(
    move(['1. 甲', '   3. 子1', '   9. 子2'], ['1. 甲', '   9. 子2', '   3. 子1']),
    ['1. 甲', '   3. 子2', '   4. 子1'],
    '子层级锚点 3 → 3,4，与顶层起始号无关'
  );

  eq(
    rn(['1. 甲', '   1. 子1', '   5. 子2']),
    ['1. 甲', '   1. 子1', '   2. 子2'],
    '子层级从 1 连号'
  );
}

console.log('\n=== 5. 无序项 / 分隔符切换打断序列 ===');
{
  eq(
    rn(['1. 甲', '   1. 子1', '- 插无序', '2. 乙']),
    ['1. 甲', '   1. 子1', '- 插无序', '2. 乙'],
    '子项后接无序项，父层仍 1,2'
  );

  eq(rn(['1. 甲', '2) 乙', '3) 丙']), ['1. 甲', '2) 乙', '3) 丙'], '`.` 与 `)` 是两个列表');
  eq(rn(['1. 甲', '1) 乙', '1) 丙']), ['1. 甲', '1) 乙', '2) 丙'], '分隔符切换后重新连号');
}

console.log('\n=== 6. 围栏 / 公式块内部不受影响 ===');
{
  eq(
    rn(['1. 甲', '   ```', '   9. 代码里的假列表', '   ```', '2. 乙']),
    ['1. 甲', '   ```', '   9. 代码里的假列表', '   ```', '2. 乙'],
    '列表项内嵌围栏：内容原样，围栏后的父项仍连号'
  );

  eq(
    rn(['1. 甲', '   1. 子1', '   ```', '   1. 代码', '   ```', '   1. 子2']),
    ['1. 甲', '   1. 子1', '   ```', '   1. 代码', '   ```', '   2. 子2'],
    '围栏隔断的子项仍按层级连号'
  );

  eq(
    rn(['1. 甲', '   $$', '   5. 公式行', '   $$', '2. 乙']),
    ['1. 甲', '   $$', '   5. 公式行', '   $$', '2. 乙'],
    '公式块内部不改'
  );
}

console.log('\n=== 7. callout（引用前缀）内独立编号 ===');
{
  eq(
    rn(['> [!note]', '> 1. 甲', '> 1. 乙', '1. 乙外']),
    ['> [!note]', '> 1. 甲', '> 2. 乙', '1. 乙外'],
    '引用内列表独立连号，不与外部串号'
  );

  eq(
    move(['> 1. 甲', '> 1. 乙'], ['> 2. 乙', '> 1. 甲']),
    ['> 1. 乙', '> 2. 甲'],
    '引用内重排同样回到起始号 1'
  );
}

console.log('\n=== 8. 空行 / 段落分隔的多个同名列表 ===');
{
  eq(
    rn(['1. 甲', '', '1. 乙', '5. 丙']),
    ['1. 甲', '', '1. 乙', '2. 丙'],
    '空行后的新列表独立从 1 起'
  );

  // 同 key 的第二个列表：快照队列按文档顺序消费，各取各的起始号
  const before = ['3. 甲', '4. 乙', '', '7. 丙', '9. 丁'];
  eq(
    move(before, ['4. 乙', '3. 甲', '', '9. 丁', '7. 丙']),
    ['3. 乙', '4. 甲', '', '7. 丁', '8. 丙'],
    '两个列表各自保留原起始号（3 与 7）'
  );
}

console.log('\n=== 9. 非列表行（续行 / 普通段落） ===');
{
  eq(
    rn(['1. 甲', '   普通续行文字', '2. 乙']),
    ['1. 甲', '   普通续行文字', '2. 乙'],
    '列表项的续行不打断层级'
  );

  eq(
    rn(['1. 甲', '普通段落', '9. 丙']),
    ['1. 甲', '普通段落', '9. 丙'],
    '顶格普通段落终止列表，丙自成锚点'
  );
}

console.log('\n=== 10. 边界 ===');
{
  eq(rn([]), [], '空数组');
  eq(rn(['纯文本', '另一行']), ['纯文本', '另一行'], '无有序项时零改动');
  eq(rn(['9. 甲', '10. 乙']), ['9. 甲', '10. 乙'], '跨 9→10 两位数正常');
  eq(rn(['99. 甲', '1. 乙']), ['99. 甲', '100. 乙'], '两位数进位到三位数');
  eq(renumberOrdered(['5. 甲', '5. 乙']).changed, true, '有变化时 changed=true');
}

console.log('\n=== 11. 幂等与不改动入参 ===');
{
  const once = move(['1. 甲', '2. 乙', '3. 丙'], ['3. 丙', '1. 甲', '2. 乙']);
  eq(renumberOrdered(once).lines, once, '对已正确的序号重复执行不累积偏移');

  const src = ['5. 甲', '5. 乙'];
  const snapshot = src.slice();
  renumberOrdered(src);
  eq(src, snapshot, '入参数组保持原样');

  const before = ['1. 甲', '2. 乙'];
  collectLayerStarts(before);
  eq(before, ['1. 甲', '2. 乙'], 'collectLayerStarts 不改动入参');
}

console.log(`\n结果：${pass} 通过，${fail} 失败\n`);
process.exit(fail ? 1 : 0);
